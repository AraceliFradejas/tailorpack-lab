import {mkdirSync,writeFileSync,readFileSync,existsSync} from 'node:fs';
import {resolve,join} from 'node:path';
import {fileURLToPath} from 'node:url';
import {createHash} from 'node:crypto';
import {runCampaign} from './campaign.mjs';
import {RoundRobinPolicy,FixedPolicy,OllamaPolicy} from './policies.mjs';
import {toCSV} from '../public/engine.js';
const args=process.argv.slice(2),allowed=['--policy','--model','--endpoint','--n','--budget','--trial','--decisions','--seeds','--out'];
if(args.length%2||args.some((a,i)=>i%2===0&&!allowed.includes(a)))throw Error(`Arguments: ${allowed.join(' ')}`);
const option=(key,fallback)=>{const i=args.indexOf(key);return i<0?fallback:args[i+1];};
const name=option('--policy','control');
if(!['control','fixed','ollama'].includes(name))throw Error('Unknown policy');
const policy=name==='ollama'?new OllamaPolicy({model:option('--model',null),endpoint:option('--endpoint','http://127.0.0.1:11434')}):name==='fixed'?new FixedPolicy():new RoundRobinPolicy();
const out=resolve(option('--out','runs/agent'));
if(existsSync(join(out,'report.json')))throw Error('Use a fresh output directory; existing reports are preserved');
const result=await runCampaign(policy,{n:Number(option('--n','17')),totalBudget:Number(option('--budget','10000')),maxTrial:Number(option('--trial','2500')),maxDecisions:Number(option('--decisions','8')),seeds:option('--seeds','10,11,12,13').split(',').map(Number)});
const base=fileURLToPath(new URL('../',import.meta.url));
result.report.sources=Object.fromEntries(['agent/campaign.mjs','agent/policies.mjs','agent/protocol.mjs','public/solver.js','public/solver-v1.js','public/search-moves.js','public/engine.js'].map(path=>[path,createHash('sha256').update(readFileSync(join(base,path))).digest('hex')]));
const csv=toCSV(result.best);result.report.candidate_sha256=createHash('sha256').update(csv).digest('hex');
mkdirSync(out,{recursive:true});
writeFileSync(join(out,'report.json'),JSON.stringify(result.report,null,2)+'\n');
writeFileSync(join(out,'candidate_NOT_VALIDATED.csv'),csv);
writeFileSync(join(out,'timings.json'),JSON.stringify({node:process.version,platform:process.platform,arch:process.arch,rows:result.timings},null,2)+'\n');
console.log(JSON.stringify({provider:result.report.provider,modelExecuted:result.report.modelExecuted,stopReason:result.report.stopReason,usedProposals:result.report.usedProposals,bestL:result.report.bestL}));
if(['policy_error','solver_error'].includes(result.report.stopReason))process.exitCode=1;
